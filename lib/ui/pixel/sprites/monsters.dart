  /// The monster for a seal: its own sprite id when it names a monster,
  /// otherwise a guess from the habit name (older seals stored `seal`).
  static PixelSprite forSeal(String spriteId, String habitName) {
    final id = kMonsterSpriteIds.contains(spriteId)
        ? spriteId
        : guessMonster(habitName);
    return all.firstWhere((s) => s.id == id);
  }
